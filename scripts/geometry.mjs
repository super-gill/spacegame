/**
 * Hull geometry from the art (docs/ship-pipeline.md, "Game side as built").
 *
 * Reads `art/ships/ships.json` (stage 1) and writes
 * `packages/sim/src/hull-geometry.ts`: for every hull in the game, its
 * outline, its radius (the outline's farthest point) and the positions of
 * the weapon and PDC mounts the art marks. The sim's hull table takes these
 * over its own numbers, so a ship is hit where it is drawn and fires from
 * where its turrets are.
 *
 * Run by `npm run geometry` and at the start of `npm run build`. The output
 * is committed; a sim test fails if it falls out of step with ships.json.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'art/ships/ships.json');
const target = path.join(root, 'packages/sim/src/hull-geometry.ts');

const round = (n) => Math.round(n * 100) / 100;

export function geometry(ships) {
  const out = {};
  for (const [id, hull] of Object.entries(ships.hulls).sort(([a], [b]) => a.localeCompare(b))) {
    if (!hull.inGame || hull.outline.length < 3) continue;
    const outline = hull.outline.map(([x, y]) => [round(x), round(y)]);
    const radius = round(Math.max(...outline.map(([x, y]) => Math.hypot(x, y))));
    const mounts = {};
    for (const m of hull.mounts) {
      if (m.type === 'high' || m.type === 'ciws') mounts[m.id] = [round(m.x), round(m.y)];
    }
    out[id] = { radius, outline, mounts };
  }
  return out;
}

export function render(ships) {
  const data = geometry(ships);
  const lines = Object.entries(data).map(([id, g]) => {
    const outline = g.outline.map(([x, y]) => `[${x}, ${y}]`).join(', ');
    const mounts = Object.entries(g.mounts).map(([m, [x, y]]) => `${m}: [${x}, ${y}]`).join(', ');
    return `  '${id}': {\n    radius: ${g.radius},\n    outline: [${outline}],\n    mounts: { ${mounts} },\n  },`;
  });
  return [
    '// Generated by scripts/geometry.mjs from art/ships/ships.json. Do not edit: change the art and run `npm run geometry`.',
    '',
    '/** A hull\'s shape from its art: outline points, radius, and weapon and PDC mount positions by mount id. */',
    'export interface HullGeometry {',
    '  radius: number;',
    '  outline: ReadonlyArray<readonly [number, number]>;',
    '  mounts: Readonly<Record<string, readonly [number, number]>>;',
    '}',
    '',
    'export const HULL_GEOMETRY: Readonly<Record<string, HullGeometry>> = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const ships = JSON.parse(fs.readFileSync(source, 'utf8'));
  const text = render(ships);
  const before = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (text !== before) fs.writeFileSync(target, text);
  console.log(`hull geometry: ${Object.keys(geometry(ships)).length} hulls${text === before ? ', unchanged' : ' -> packages/sim/src/hull-geometry.ts'}`);
}
